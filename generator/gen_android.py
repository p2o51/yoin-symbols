# ------------------------------------------------------------------ VectorDrawable

def vector_drawable(ic) -> str:
    out = [
        '<?xml version="1.0" encoding="utf-8"?>',
        f"<!-- Yoin Symbols · {ic.name} · {HEADER} -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="24dp"',
        '    android:height="24dp"',
        '    android:viewportWidth="24"',
        '    android:viewportHeight="24"',
    ]
    if ic.name in MIRRORED:
        out.append('    android:autoMirrored="true"')
    out[-1] += ">"
    cur = None
    for ly in ic.layers:
        g = ly.get("group")
        if g != cur:
            if cur is not None:
                out.append("    </group>")
            if g is not None:
                out.append(f'    <group android:name="{g}">')
            cur = g
        ind = "        " if g else "    "
        attrs = []
        if ly.get("id"):
            attrs.append(f'android:name="{ly["id"]}"')
        attrs.append(f'android:pathData="{to_d(ly["d"])}"')
        if ly["mode"] in ("stroke", "fillstroke"):
            attrs += ['android:strokeColor="#FF000000"', 'android:strokeWidth="1.5"',
                      'android:strokeLineCap="round"', 'android:strokeLineJoin="round"']
        if ly["mode"] in ("fill", "fillstroke"):
            attrs.append('android:fillColor="#FF000000"')
            if ly.get("rule") == "evenodd":
                attrs.append('android:fillType="evenOdd"')
        else:
            attrs.append('android:fillColor="#00000000"')
        out.append(f"{ind}<path")
        for i, a in enumerate(attrs):
            out.append(f"{ind}    {a}" + (" />" if i == len(attrs) - 1 else ""))
    if cur is not None:
        out.append("    </group>")
    out.append("</vector>")
    return "\n".join(out) + "\n"


# ------------------------------------------------------------------ ImageVector catalog

def _kt_layer(ly, indent) -> str:
    d = to_d(ly["d"])
    if ly["mode"] == "stroke":
        return f'{indent}stroke("{d}")'
    if ly["mode"] == "fillstroke":
        return f'{indent}fillStroke("{d}")'
    if ly.get("rule") == "evenodd":
        return f'{indent}fill("{d}", evenOdd = true)'
    return f'{indent}fill("{d}")'


def catalog_kt() -> str:
    lines = [
        f"// {HEADER}",
        "@file:Suppress(\"ktlint\", \"MaxLineLength\")",
        "",
        f"package {KOTLIN_PACKAGE}",
        "",
        "import androidx.compose.ui.graphics.vector.ImageVector",
        "",
        "/**",
        " * Yoin Symbols: 24 dp line icons with a 1.5 dp stroke, round caps and joins, and",
        " * continuous-curvature containers.",
        " *",
        " * ```",
        " * Icon(YoinSymbols.Translate, contentDescription = \"Translate lyrics\")",
        " * ```",
        " *",
        " * Paths are drawn in black and take the tint of the `Icon` that shows them.",
        " * Every vector is built lazily on first use.",
        " */",
        "public object YoinSymbols {",
    ]
    for n in names():
        ic = REGISTRY[n]
        prop = pascal(n)
        lines.append(f"    /** {ic.zh} · `{n}` */")
        lines.append(f"    public val {prop}: ImageVector by lazy {{")
        mirror = ", autoMirror = true" if n in MIRRORED else ""
        lines.append(f'        symbol("{prop}"{mirror}) {{')
        cur = None
        for ly in ic.layers:
            g = ly.get("group")
            if g != cur:
                if cur is not None:
                    lines.append("            }")
                if g is not None:
                    lines.append(f'            group("{g}") {{')
                cur = g
            lines.append(_kt_layer(ly, "                " if g else "            "))
        if cur is not None:
            lines.append("            }")
        lines.append("        }")
        lines.append("    }")
        lines.append("")
    lines[-1] = "}"
    lines.append("")
    # names map lives in its own object so the catalog stays tree-shakable
    lines += [
        "/** Every symbol by its canonical snake_case name, for galleries and pickers. */",
        "public object YoinSymbolCatalog {",
        "    public val all: Map<String, () -> ImageVector> = linkedMapOf(",
    ]
    lines += [f'        "{n}" to {{ YoinSymbols.{pascal(n)} }},' for n in names()]
    lines += ["    )", "}", ""]
    return "\n".join(lines)


# ------------------------------------------------------------------ shape data for animated symbols

def _kf(v) -> str:
    s = f"{v:.3f}".rstrip("0").rstrip(".")
    return ("0" if s in ("-0", "") else s) + "f"


def _floats(vals) -> str:
    return ", ".join(_kf(v) for v in vals)


def _pts(pts) -> str:
    flat = []
    for x, y in pts:
        flat += [x, y]
    return f"floatArrayOf({_floats(flat)})"


