def build() -> int:
    res = LIB / "res" / "drawable"
    res.mkdir(parents=True, exist_ok=True)
    keep = set()
    for n in names():
        fn = f"{RES_PREFIX}{n}.xml"
        write(res / fn, vector_drawable(REGISTRY[n]))
        keep.add(fn)
    for stale in res.glob(f"{RES_PREFIX}*.xml"):
        if stale.name not in keep:
            stale.unlink()
    write(KT / "YoinSymbols.kt", catalog_kt())
    write(KT / "SymbolGeometry.kt", geometry_kt())
    return len(keep)
