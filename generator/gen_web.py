def build(font_ttf, font_woff2) -> int:
    write(DIST / "index.js", index_js())
    write(DIST / "index.d.ts", index_dts())
    write(DIST / "react.js", react_js())
    write(DIST / "react.d.ts", react_dts())
    write(DIST / "sprite.svg", sprite())
    write(DIST / "meta.json", json.dumps(dict(version=version(), groups=GROUP_EN, symbols=meta()), ensure_ascii=False, indent=1) + "\n")
    (WEB / "font").mkdir(parents=True, exist_ok=True)
    shutil.copyfile(font_ttf, WEB / "font" / f"{FONT_FAMILY}.ttf")
    shutil.copyfile(font_woff2, WEB / "font" / f"{FONT_FAMILY}.woff2")
    write(WEB / "font" / "yoin-symbols.css", font_css())
    svg_out = WEB / "svg"
    if svg_out.exists():
        shutil.rmtree(svg_out)
    shutil.copytree(ROOT / "svg", svg_out)
    write(WEB / "package.json", package_json())
    shutil.copyfile(ROOT / "LICENSE", WEB / "LICENSE")
    return len(names())
