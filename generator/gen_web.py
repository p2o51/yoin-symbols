"""web/: the npm package `yoin-symbols` (SVG strings, React components, sprite, icon font)."""
from __future__ import annotations

import json
import shutil

from common import (
    FONT_DISPLAY, FONT_FAMILY, GROUP_EN, NPM_NAME, REGISTRY, REPO_URL, ROOT, codepoints, meta, names,
    pascal, svg_markup, to_d, version, write,
)

WEB = ROOT / "web"
DIST = WEB / "dist"


def _nodes(ic):
    """Flat list of [tag, attrs] for React."""
    out = []
    for ly in ic.layers:
        attrs = {"d": to_d(ly["d"])}
        if ly["mode"] == "fill":
            attrs.update(fill="currentColor", stroke="none")
            if ly.get("rule") == "evenodd":
                attrs["fillRule"] = "evenodd"
        elif ly["mode"] == "fillstroke":
            attrs["fill"] = "currentColor"
        out.append(["path", attrs])
    return out


def index_js() -> str:
    lines = [
        f"// {NPM_NAME} {version()} · generated by generator/build.py",
        "",
    ]
    for n in names():
        svg = svg_markup(REGISTRY[n], size=24, title=False, ids=False)
        lines.append(f"/** {REGISTRY[n].zh} · {n} */")
        lines.append(f"export const {pascal(n)} = {json.dumps(svg)};")
    lines += [
        "",
        "/** Every symbol by canonical name. Importing this pulls in the whole set. */",
        "export const symbols = {",
    ]
    lines += [f"  {json.dumps(n)}: {pascal(n)}," for n in names()]
    lines += [
        "};",
        "",
        "export const names = Object.keys(symbols);",
        "",
        "const escape = (s) => String(s).replace(/[&<>\"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '\"': '&quot;' })[c]);",
        "",
        "/**",
        " * Returns an SVG string for a symbol.",
        " * @param {string} name  canonical name, e.g. \"translate\"",
        " * @param {{size?: number|string, strokeWidth?: number|string, className?: string, title?: string}} [options]",
        " */",
        "export function toSvg(name, options = {}) {",
        "  const svg = symbols[name];",
        "  // RangeError, not Error: this module exports a symbol named `Error`.",
        "  if (!svg) throw new RangeError(`Unknown Yoin symbol: ${name}`);",
        "  const { size = 24, strokeWidth = 1.5, className, title } = options;",
        "  let out = svg",
        "    .replace('width=\"24\" height=\"24\"', `width=\"${escape(size)}\" height=\"${escape(size)}\"`)",
        "    .replace('stroke-width=\"1.5\"', `stroke-width=\"${escape(strokeWidth)}\"`);",
        "  const extra = (className ? ` class=\"${escape(className)}\"` : '') + (title ? ' role=\"img\"' : ' aria-hidden=\"true\"');",
        "  out = out.replace('<svg ', `<svg${extra} `);",
        "  if (title) out = out.replace(/(<svg[^>]*>)/, `$1<title>${escape(title)}</title>`);",
        "  return out;",
        "}",
        "",
    ]
    return "\n".join(lines)


def index_dts() -> str:
    lines = [f"// {NPM_NAME} {version()} · generated by generator/build.py", ""]
    union = "\n".join(f"  | {json.dumps(n)}" for n in names())
    lines.append(f"export type YoinSymbolName =\n{union};")
    lines.append("")
    for n in names():
        lines.append(f"/** {REGISTRY[n].zh} · {n} */")
        lines.append(f"export declare const {pascal(n)}: string;")
    lines += [
        "",
        "export declare const symbols: Record<YoinSymbolName, string>;",
        "export declare const names: YoinSymbolName[];",
        "",
        "export interface ToSvgOptions {",
        "  size?: number | string;",
        "  strokeWidth?: number | string;",
        "  className?: string;",
        "  /** Accessible name. Without it the SVG is aria-hidden. */",
        "  title?: string;",
        "}",
        "",
        "export declare function toSvg(name: YoinSymbolName, options?: ToSvgOptions): string;",
        "",
    ]
    return "\n".join(lines)


def react_js() -> str:
    lines = [
        f"// {NPM_NAME}/react {version()} · generated by generator/build.py",
        "import { createElement, forwardRef } from 'react';",
        "",
        "const base = {",
        "  xmlns: 'http://www.w3.org/2000/svg',",
        "  viewBox: '0 0 24 24',",
        "  fill: 'none',",
        "  stroke: 'currentColor',",
        "  strokeLinecap: 'round',",
        "  strokeLinejoin: 'round',",
        "};",
        "",
        "function create(displayName, nodes) {",
        "  const Component = forwardRef(function YoinSymbol({ size = 24, strokeWidth = 1.5, title, children, ...rest }, ref) {",
        "    const a11y = title ? { role: 'img' } : { 'aria-hidden': true };",
        "    return createElement(",
        "      'svg',",
        "      { ...base, width: size, height: size, strokeWidth, ...a11y, ...rest, ref },",
        "      title ? createElement('title', null, title) : null,",
        "      ...nodes.map(([tag, attrs], i) => createElement(tag, { key: i, ...attrs })),",
        "      children,",
        "    );",
        "  });",
        "  Component.displayName = displayName;",
        "  return Component;",
        "}",
        "",
    ]
    for n in names():
        lines.append(f"/** {REGISTRY[n].zh} · {n} */")
        lines.append(f"export const {pascal(n)} = /* @__PURE__ */ create({json.dumps(pascal(n))}, {json.dumps(_nodes(REGISTRY[n]), ensure_ascii=False)});")
    lines += [
        "",
        "// `…Icon` aliases, for names that would shadow globals (Error, Storage, Gamepad) or your own components.",
        "export {",
    ]
    lines += [f"  {pascal(n)} as {pascal(n)}Icon," for n in names()]
    lines += ["};", ""]
    return "\n".join(lines)


def react_dts() -> str:
    lines = [
        f"// {NPM_NAME}/react {version()} · generated by generator/build.py",
        "import type { ForwardRefExoticComponent, RefAttributes, SVGProps } from 'react';",
        "",
        "export interface YoinSymbolProps extends Omit<SVGProps<SVGSVGElement>, 'ref'> {",
        "  /** Width and height. Default 24. */",
        "  size?: number | string;",
        "  /** Default 1.5. */",
        "  strokeWidth?: number | string;",
        "  /** Accessible name. Without it the SVG is aria-hidden. */",
        "  title?: string;",
        "}",
        "",
        "export type YoinSymbolComponent = ForwardRefExoticComponent<YoinSymbolProps & RefAttributes<SVGSVGElement>>;",
        "",
    ]
    for n in names():
        lines.append(f"/** {REGISTRY[n].zh} · {n} */")
        lines.append(f"export declare const {pascal(n)}: YoinSymbolComponent;")
    lines += ["", "// `…Icon` aliases"]
    lines += [f"export declare const {pascal(n)}Icon: YoinSymbolComponent;" for n in names()]
    lines.append("")
    return "\n".join(lines)


def sprite() -> str:
    parts = ['<svg xmlns="http://www.w3.org/2000/svg" style="display:none">']
    for n in names():
        inner = svg_markup(REGISTRY[n], size=24, title=False, ids=False)
        inner = inner[inner.index(">") + 1: -len("</svg>")]
        parts.append(
            f'<symbol id="{n}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" '
            f'stroke-linecap="round" stroke-linejoin="round">{inner}</symbol>'
        )
    parts.append("</svg>")
    return "\n".join(parts) + "\n"


def font_css() -> str:
    cps = codepoints()
    lines = [
        f"/* {NPM_NAME} {version()} · icon font · generated by generator/build.py */",
        "@font-face {",
        f"  font-family: \"{FONT_DISPLAY}\";",
        "  font-style: normal;",
        "  font-weight: 400;",
        "  font-display: block;",
        f"  src: url(\"./{FONT_FAMILY}.woff2\") format(\"woff2\"), url(\"./{FONT_FAMILY}.ttf\") format(\"truetype\");",
        "}",
        "",
        ".ys {",
        f"  font-family: \"{FONT_DISPLAY}\";",
        "  font-weight: normal;",
        "  font-style: normal;",
        "  font-size: 24px;",
        "  line-height: 1;",
        "  display: inline-block;",
        "  vertical-align: middle;",
        "  speak: never;",
        "  -webkit-font-smoothing: antialiased;",
        "}",
        "",
    ]
    for n in names():
        lines.append(f".ys-{n.replace('_', '-')}::before {{ content: \"\\{cps[n]:x}\"; }}")
    lines.append("")
    return "\n".join(lines)


